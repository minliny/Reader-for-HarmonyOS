import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { applyQidianDirectoryCorrection, QIDIAN_CHAPTER_LIST, QIDIAN_PREVIOUS_FINGERPRINT } from './qidian-directory-source-correction.mjs';
import { ruleFingerprint } from './source-supply-lib.mjs';
const sources = JSON.parse(readFileSync(new URL('../entry/src/main/resources/rawfile/reader-tested-book-source-collection.json', import.meta.url)));
const actual = sources.find(s => s.builtinId === 'reader-builtin-qidian');
const untouchedSupply = structuredClone(sources);
const original = structuredClone(actual);
original.builtinVersion = 6;
original.ruleToc.chapterList = '.y-list__item@a,._chapterBar_fps9g_592';
delete original.provenance.directoryCorrection;
original.ruleFingerprint = ruleFingerprint(original);
assert.equal(original.ruleFingerprint, QIDIAN_PREVIOUS_FINGERPRINT);
const before = structuredClone(original);
const corrected = applyQidianDirectoryCorrection([original]);
assert.equal(corrected.ruleToc.chapterList, QIDIAN_CHAPTER_LIST);
assert.equal(corrected.ruleToc.isVolume, before.ruleToc.isVolume);
assert.equal(corrected.bookSourceUrl, before.bookSourceUrl);
assert.equal(corrected.verifiedAt, before.verifiedAt);
assert.deepEqual(corrected.capabilities, before.capabilities);
const correctedSnapshot = structuredClone(corrected);
assert.deepEqual(applyQidianDirectoryCorrection([corrected]), correctedSnapshot);
assert.deepEqual(sources, untouchedSupply, 'tool verification must not upgrade the bundled supply');
assert.equal(corrected.builtinVersion, 7);
assert.equal(corrected.provenance.directoryCorrection.previousRuleFingerprint, QIDIAN_PREVIOUS_FINGERPRINT);
const customized = structuredClone(before);
customized.ruleToc.chapterName = 'user-rule';
assert.throws(() => applyQidianDirectoryCorrection([customized]), /different source revision/);
console.log('Qidian builtin directory correction: PASS');
