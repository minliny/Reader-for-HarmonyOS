import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { assertSourceLoginDefault } from './source-login-default-policy.mjs';
import { isExternalBundledSource } from './source-supply-lib.mjs';
const root=new URL('../entry/src/main/resources/rawfile/',import.meta.url);
const sha=text=>createHash('sha256').update(text).digest('hex');
const document=readFileSync(new URL('reader-tested-book-source-collection.json',root),'utf8');
const sources=JSON.parse(document), byId=new Map(sources.map(s=>[s.bookSourceUrl,s]));
sources.forEach(assertSourceLoginDefault);
assert.ok(sources.every(source=>!isExternalBundledSource(source)), 'bundled collection contains external-media sources');
const digest=sha(document);
const bundleId='reader-tested-book-sources-v2';
const ownerFile=new URL('../entry/src/main/ets/app/ReaderRuntimeOwner.ts',import.meta.url);
const owner=readFileSync(ownerFile,'utf8');
const digestMarker=/const BUNDLED_RAW_FILE_SHA256 = '[0-9a-f]{64}';/;
assert.ok(digestMarker.test(owner),'bundled source digest declaration is missing');
const updatedOwner=owner.replace(digestMarker,`const BUNDLED_RAW_FILE_SHA256 = '${digest}';`);
const dir=new URL('bundled-sources/',root), check=process.argv.includes('--check');
if(!check)mkdirSync(dir,{recursive:true});
const outputs=new Map();
const items=[];
for(const [sourceId,source] of byId){
 const document=JSON.stringify(source)+'\n',itemDigest=sha(document),file=sha(sourceId)+'.json';
 outputs.set(file,document);items.push({sourceId,itemDigest,file:'bundled-sources/'+file});
}
const index=JSON.stringify({schemaVersion:1,bundleId,digest,collectionRecords:sources.length,items})+'\n';
outputs.set('index.json',index);
for(const [file,content] of outputs){
 if(check)assert.equal(readFileSync(new URL(file,dir),'utf8'),content,file+' is stale');
 else writeFileSync(new URL(file,dir),content);
}
for(const file of readdirSync(dir))if(!outputs.has(file)){if(check)assert.fail('stale generated resource '+file);else rmSync(new URL(file,dir));}
const constants=new URL('../entry/src/main/ets/app/BundledSourceIndexIdentity.ts',import.meta.url);
const content=`// Generated by tools/generate-bundled-source-index.mjs.\nexport const BUNDLED_SOURCE_BUNDLE_ID = '${bundleId}';\nexport const BUNDLED_SOURCE_INDEX_SHA256 = '${sha(index)}';\n`;
if(check)assert.equal(readFileSync(constants,'utf8'),content);else writeFileSync(constants,content);
if(check)assert.equal(owner,updatedOwner,'runtime bundled collection digest is stale');
else if (owner!==updatedOwner)writeFileSync(ownerFile,updatedOwner);
console.log(`bundled source index ${check?'verified':'generated'}: ${items.length} preferred identities`);
