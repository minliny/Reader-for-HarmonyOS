#!/usr/bin/env node
/**
 * Generates a deterministic, fully synthetic novel fixture for the isolated
 * visual-acceptance branch. It reads no external files and performs no network
 * requests.
 *
 *   node tools/generate-visual-novel-fixtures.mjs [output-path]
 *
 * Pass `-` as output-path to print the generated TypeScript to stdout.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = process.argv[2] ?? path.join(SCRIPT_DIR, '..',
  'entry/src/main/ets/app/visual/fixtures/FixtureNovelText.ts');
const MIN_SECTION_CHARS = 2000;
const PARAGRAPHS_PER_CHAPTER = 20;

const NOVEL_TITLE = '云港巡灯录';
const NOVEL_AUTHOR = '视觉验收编写组';
const CHAPTER_TITLES = [
  '清晨校准',
  '风向记录',
  '旧桥巡检',
  '潮位刻度',
  '灯塔回声',
  '雨棚清单',
  '夜航标记',
  '仓库钥匙',
  '广场钟声',
  '河堤脚印',
  '雾中信号',
  '纸船归来',
  '北岸来客',
  '星图复核',
  '最后一盏灯',
  '黎明交接',
];
const LOCATIONS = ['东堤', '旧桥', '北岸', '钟楼', '仓库', '灯塔'];
const CONDITIONS = ['薄雾', '微雨', '顺风', '退潮', '晴空', '夜色'];
const TASKS = ['灯号', '潮位', '备用电池', '门锁', '航标', '交接表'];
const FINDINGS = [
  '所有刻度都与上一班记录一致',
  '远处回声按固定间隔返回',
  '备用线路在切换后保持稳定',
  '巡检路线没有出现遗漏标记',
  '窗沿积水已经降到警戒线以下',
  '值班表上的时间戳连续且清晰',
];
const DECISIONS = [
  '把结果写入今日交接页',
  '在下一轮巡检时再次复核',
  '给对应设备贴上蓝色确认签',
  '将异常项保留为普通观察记录',
  '按既定顺序继续余下检查',
  '通知下一班关注同一处刻度',
];

function buildParagraph(chapterIndex, paragraphIndex, title) {
  const location = LOCATIONS[(chapterIndex + paragraphIndex) % LOCATIONS.length];
  const condition = CONDITIONS[(chapterIndex * 2 + paragraphIndex) % CONDITIONS.length];
  const task = TASKS[(chapterIndex + paragraphIndex * 3) % TASKS.length];
  const finding = FINDINGS[(chapterIndex * 3 + paragraphIndex) % FINDINGS.length];
  const decision = DECISIONS[(chapterIndex + paragraphIndex * 2) % DECISIONS.length];
  return `第${chapterIndex + 1}章“${title}”第${paragraphIndex + 1}段：巡灯员在${location}核对${condition}下的${task}，将灯号、潮位和脚步声写进蓝色表格。她确认${finding}，随后${decision}。人物、地点、事件和数值均由程序合成，仅用于分页、选中、书签与进度视觉测试。交接前她复读记录，保证标点完整并便于下一班继续。`;
}

const chapters = CHAPTER_TITLES.map((title, chapterIndex) => {
  const paragraphs = [];
  for (let paragraphIndex = 0; paragraphIndex < PARAGRAPHS_PER_CHAPTER; paragraphIndex++) {
    paragraphs.push(buildParagraph(chapterIndex, paragraphIndex, title));
  }
  const content = paragraphs.join('\n');
  if (content.length < MIN_SECTION_CHARS) {
    throw new Error(`synthetic chapter ${chapterIndex + 1} has only ${content.length} chars`);
  }
  if (content.includes('`') || content.includes('${')) {
    throw new Error(`synthetic chapter ${chapterIndex + 1} contains a template-literal escape`);
  }
  return { title, content };
});

const totalChars = chapters.reduce((sum, chapter) => sum + chapter.content.length, 0);
const body = chapters.map((chapter) =>
  `  {\n    title: ${JSON.stringify(chapter.title)},\n    content: \`${chapter.content}\`,\n  },`).join('\n');

const file = `// Deterministic synthetic text for the isolated visual-acceptance branch.
// Generated by tools/generate-visual-novel-fixtures.mjs; no external source material is used.
// Characters, locations, events, and measurements are entirely fictional test data.
// Regenerate this file instead of editing chapter content by hand.
export const NOVEL_TITLE = ${JSON.stringify(NOVEL_TITLE)};
export const NOVEL_AUTHOR = ${JSON.stringify(NOVEL_AUTHOR)};

export interface FixtureNovelChapter {
  title: string;
  content: string;
}

export const NOVEL_CHAPTERS: FixtureNovelChapter[] = [
${body}
];
`;

if (OUTPUT_PATH === '-') {
  process.stdout.write(file);
} else {
  fs.writeFileSync(OUTPUT_PATH, file, 'utf8');
  console.log(`wrote ${OUTPUT_PATH}`);
  console.log(`chapters: ${chapters.length}, total chars: ${totalChars}`);
}
