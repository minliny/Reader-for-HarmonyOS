test('all bookshelf projections decode the same identities and lightweight membership remains sparse', async () => {
  const [full, row, membership] = await Promise.all([loadShelf('full'), loadShelf('row'), loadShelf('membership')]);
  const facts = (book: ShelfBook) => [book.sourceId, book.bookId, book.contentKind];
  const expected = [
    ['source', 'book', 'manga'],
    ['local', 'fixture-local-txt', 'text'],
    ['fixture-edition', 'https://books.example.test/fixture-novel', 'text'],
    ['fixture-saved', 'https://books.example.test/fixture-novel', 'text'],
  ];
  for (const view of [full, row, membership]) {
    assert.equal(view.total, 4);
    assert.deepEqual(view.books.map(facts), expected);
  }
  assert.equal(full.books[0].chapterCount, 2);
  assert.equal(row.books[0].chapterCount, 2);
  assert.equal(membership.books[0].chapterCount, 0);
  for (const book of fixture.bookshelf.membership.books) {
    for (const heavy of ['chapterCount', 'readProgress', 'readingPosition', 'currentChapterTitle', 'currentChapterIndex'])
      assert.equal(Object.hasOwn(book, heavy), false);
  }
});

test('a grouped result highlights a saved variant and selection resolves that same exact shelf identity', async () => {
  const [primary, alternate] = await searchBooks();
  assert.equal(primary.sourceId, 'fixture-primary');
  assert.equal(alternate.sourceId, 'fixture-saved');
  const saved = (await loadShelf('membership')).books.filter(book => book.sourceId !== 'fixture-edition');
  const view = new SearchViewState();
  const grouped = new SearchResultProjection().update([primary, alternate], saved, 'Fixture novel', view);
  assert.equal(grouped.orderedKeys.length, 1);
  const row = grouped.rows.get(grouped.orderedKeys[0])!;
  assert.equal(row.book.sourceId, primary.sourceId);
  assert.equal(row.inBookshelf, true);
  const selected = resolveBookshelfBook(row.book, row.variants, saved);
  assert.equal(selected.kind, 'matched');
  if (selected.kind === 'matched') assert.equal(selected.book.sourceId, alternate.sourceId);
});

test('an on-shelf badge can describe multiple saved versions without silently merging them', async () => {
  const results = await searchBooks();
  const saved = (await loadShelf('membership')).books;
  const grouped = new SearchResultProjection().update(results, saved, 'Fixture novel', new SearchViewState());
  const row = grouped.rows.get(grouped.orderedKeys[0])!;
  assert.equal(row.inBookshelf, true);
  assert.deepEqual(resolveBookshelfBook(row.book, row.variants, saved), { kind: 'ambiguous' });
});

test('a malformed media kind triggers production bookshelf decoding failure', async () => {
  const membership = fixture.bookshelf.membership;
  const wire = { ...membership, books: [{ ...membership.books[0], contentKind: 'unknown' }] };
  const gateway = new ReaderCoreGateway(coreTransport('bookshelf.list', wire));
  await assert.rejects(gateway.loadBookshelf({ pageProjection: true, membershipOnly: true, limit: 48 }), /invalid shelf contentKind/);
});

test('switch commit and rollback agree on the transaction and reverse the book and progress identities', () => {
  const { commit, rollback } = fixture.sourceSwitch;
  assert.equal(commit.phase, 'pending');
  assert.equal(rollback.phase, 'rolledBack');
  assert.equal(rollback.changed, true);
  assert.equal(typeof commit.transactionId, 'string');
  assert.ok(commit.transactionId.length > 0);
  assert.equal(rollback.transactionId, commit.transactionId);
  assert.deepEqual([commit.book.sourceId, commit.book.bookId], ['source-new', 'book-new']);
  assert.deepEqual([commit.progress.sourceId, commit.progress.bookId], ['source-new', 'book-new']);
  assert.equal(commit.matchedChapter.order, 1);
  assert.deepEqual([rollback.restoredBook.sourceId, rollback.restoredBook.bookId], ['source-old', 'book-old']);
  assert.deepEqual([rollback.restoredProgress.sourceId, rollback.restoredProgress.bookId], ['source-old', 'book-old']);
  assert.equal(rollback.restoredProgress.chapterOffset, 88);
});
