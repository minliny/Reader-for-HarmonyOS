const bytes = readFileSync(snapshot);
const fixture = JSON.parse(bytes.toString('utf8'));

function coreTransport(method: string, data: object, checkParams: (params: Record<string, unknown>) => void = () => {}): ReaderRuntimeOwner {
  return {
    async request(actualMethod: string, params: Record<string, unknown>) {
      assert.equal(actualMethod, method);
      checkParams(params);
      return { data };
    },
    supportsCoreCapability(capability: string) { return capability === 'bookshelf.anchorPage.v1'; },
  } as unknown as ReaderRuntimeOwner;
}

async function loadShelf(projection: 'full' | 'row' | 'membership') {
  const params: BookshelfListParams = projection === 'full' ? {} : { pageProjection: true, offset: 0, limit: 48,
    ...(projection === 'membership' ? { membershipOnly: true } : {}) };
  const request = coreTransport('bookshelf.list', fixture.bookshelf[projection], sent => assert.deepEqual(sent, params));
  return new ReaderCoreGateway(request).loadBookshelf(params);
}

async function searchBooks(): Promise<SearchBook[]> {
  const results: SearchBook[] = [];
  for (const response of fixture.search.responses) {
    const source: SearchSource = { sourceId: response.sourceId, sourceVersion: response.sourceVersion,
      name: response.sourceId, enabled: true, category: 'novel' };
    const request = coreTransport('book.search', response, sent => {
      assert.equal(sent.sourceId, source.sourceId);
      assert.equal(sent.keyword, 'Fixture novel');
    });
    const outcome = await new SearchGateway(request).searchBySource(source, 'Fixture novel', undefined, 'fixture-query');
    assert.equal(outcome.ok, true);
    if (outcome.ok) results.push(...outcome.results);
  }
  return results;
}

